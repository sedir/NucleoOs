#!/usr/bin/env python3
"""Build APK1 Portuguese frozen-answer retrieval. Standard library only; no device writes.

The index is scanned sequentially; only one bounded alias and 16 query term hashes
are resident. Matching covers every salient query term, requires specificity and
rejects tied answers. It is lexical retrieval, not neural inference or generation.
"""
import argparse, hashlib, json, re, struct, unicodedata
from pathlib import Path
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
LEX = json.loads((HERE / 'lexicon.json').read_text())
STOP = set(LEX['stop'].split())
SYN = LEX['synonyms']
MAX_TERMS = 16

def fold(s):
    return ''.join(c for c in unicodedata.normalize('NFD', s.lower()) if unicodedata.category(c) != 'Mn')

def terms(s):
    ts = re.findall(r'[a-z0-9]+', fold(s))
    if any(len(t) >= 48 for t in ts): return []
    return sorted({SYN.get(t,t) for t in ts if t not in STOP})

def hashed(t):
    h = 14695981039346656037
    for c in t.encode(): h = ((h ^ c) * 1099511628211) & ((1<<64)-1)
    return h

def load_cards():
    cards = {c['id']:c for l in (HERE/'corpus.jsonl').read_text().splitlines() if l.strip() for c in [json.loads(l)]}
    for l in (HERE/'overrides.jsonl').read_text().splitlines():
        if not l.strip() or l.startswith('//'): continue
        c = json.loads(l)
        if c.get('exclude'): cards.pop(c['id'],None); continue
        cards[c['id']] = {**cards.get(c['id'],{}), **c, 'reviewed':True}
    return sorted(cards.values(),key=lambda c:c['id'])

def build():
    cards=load_cards()
    surnames={}
    for c in cards:
        if c['category']=='person':
            name=c['ask'][0].strip().split()[-1]; key=fold(name)
            surnames.setdefault(key,[]).append(c['id'])
    aliases=[]; blob=bytearray(); categories={}; indexed=0
    for ci,c in enumerate(cards):
        if not c.get('ask') or not c.get('reply') or '▁' in c['reply']: raise ValueError(c['id'])
        off=len(blob); reply=c['reply'].strip().encode(); cid=c['id'].encode()
        # No mid-codepoint or mid-sentence truncation. Long cards stay in the source for review.
        if len(reply)>1000 or len(cid)>63: continue
        # Imported paraphrases sometimes ask for facts absent from the short answer. Only
        # definition/identity prompts are imported; reviewed overrides can carry specific facts.
        asks=c['ask'] if c.get('reviewed') or c['category']=='person' else [q for q in c['ask'] if re.match(r'^(o que (e|sao)|quem (e|foi)|explique|defina|o significado de)\b',fold(q))]
        if c['category']=='person':
            name=c['ask'][0].strip().split()[-1]
            if len(name)>=4 and len(surnames[fold(name)])==1: asks=[*asks, name]
        unique=set()
        for q in asks:
            ts=terms(q)
            if not 1<=len(ts)<=MAX_TERMS: continue
            hs=tuple(sorted(hashed(t) for t in ts))
            if hs in unique: continue
            unique.add(hs);aliases.append((ci,off,hs))
        if not unique: continue
        blob+=struct.pack('<H',len(cid))+cid+struct.pack('<H',len(reply))+reply
        indexed+=1;categories[c['category']]=categories.get(c['category'],0)+1
    start=16+sum(9+8*len(hs) for _,_,hs in aliases)
    body=bytearray(b'APK1'+struct.pack('<III',len(aliases),start,start+len(blob)))
    for ci,off,hs in aliases: body+=struct.pack('<IIB',ci,start+off,len(hs))+struct.pack('<'+'Q'*len(hs),*hs)
    body+=blob
    inputs=['corpus.jsonl','overrides.jsonl','lexicon.json','build.py']
    source_sha=hashlib.sha256(b''.join(n.encode()+b'\0'+(HERE/n).read_bytes().replace(b'\r\n',b'\n') for n in inputs)).hexdigest()
    prov=dict(schema=1,format='APK1',language='pt-BR',retrieval='all-term-coverage; specificity >= 0.60; distinct-answer margin >= 0.15',
              cards=indexed,aliases=len(aliases),categories=categories,bytes=len(body),sha256=hashlib.sha256(body).hexdigest(),source_sha256=source_sha)
    return bytes(body),json.dumps(prov,ensure_ascii=False,indent=2)+'\n'

def header():
    s='// Generated by tools/anima/pt/build.py; shared with the pack normalizer.\n'
    s+='static const char *const PTK_STOP[] = {'+','.join(json.dumps(t) for t in sorted(STOP))+',NULL};\n'
    s+='static const struct { const char *from, *to; } PTK_SYN[] = {\n'
    s+=''.join('{'+json.dumps(k)+','+json.dumps(v)+'},\n' for k,v in sorted(SYN.items()))+'{NULL,NULL}};\n'
    return s

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--out',type=Path)
    a=p.parse_args();body,prov=build()
    targets=[a.out] if a.out else [ROOT/'tools/sd-sim/data/anima'] if a.check else [ROOT/d for d in ['tools/sd-sim/data/anima','tools/anima-host/sd/data/anima','deploy/sd-safe/data/anima','deploy/sd/data/anima']]
    generated={ROOT/'firmware/components/nucleo_anima/anima_pt_lexicon.h':header().encode()}
    for dest in targets:
        generated[dest/'anima-pt-knowledge.bin']=body;generated[dest/'anima-pt-knowledge.bin.prov']=prov.encode()
    for path,data in generated.items():
        if a.check:
            if not path.exists() or path.read_bytes()!=data: raise SystemExit(f'Stale Portuguese pack: {path}')
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print(prov)
if __name__=='__main__': main()
